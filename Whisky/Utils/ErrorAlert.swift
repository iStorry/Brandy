import AppKit

/// Tells the person that something they asked for failed, instead of only logging it
@MainActor
enum ErrorAlert {
    static func show(_ title: String, error: Error) {
        show(title, message: error.localizedDescription)
    }

    static func show(_ title: String, message: String) {
        let alert = NSAlert()
        alert.messageText = title
        alert.informativeText = message
        alert.alertStyle = .critical
        alert.addButton(withTitle: String(localized: "button.ok"))
        alert.runModal()
    }
}
